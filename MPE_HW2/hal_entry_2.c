void R_External_Interrupt(external_irq_callback_args_t *p_args) // Interrupt Service Routine
{
    switch (p_args->channel)
    {
    case EXTERNAL_INTERRUPT_11:
        state.task_mode_11 ^= state_mask;
        break;
    case EXTERNAL_INTERRUPT_12:
        state.task_mode_12 ^= state_mask;
        break;
    case EXTERNAL_INTERRUPT_13:
        state.task_mode_13 ^= state_mask;
        break;
    case EXTERNAL_INTERRUPT_14:
        state.task_mode_14 = state_mask;
        R_IOPORT_PinWrite(&g_ioport_ctrl, BSP_IO_PORT_11_PIN_00, BSP_IO_LEVEL_LOW);
        break;
    }
}
void R_AGT0_Interrupt(timer_callback_args_t *p_args)
{
    FSP_PARAMETER_NOT_USED(p_args);
    agt0_counter++;

    ////////////// YOU MUST EDIT ONLY HERE ABOUT Assignment 2-1 ///////////////
    if (state.task_mode_11 == 0x01) // (led toggle on)
    {
        if (agt0_counter % 10 == 0) // 100ms
        {
            LED_PA08_Enable_Level ^= 0x01;
            R_IOPORT_PinWrite(&g_ioport_ctrl, led_pin[0], LED_PA08_Enable_Level);
        }
    }
    else // task_mode_11 == 0x00 (led toggle off)
    {
        LED_PA08_Enable_Level = 0x01;
        R_IOPORT_PinWrite(&g_ioport_ctrl, led_pin[0], LED_PA08_Enable_Level);
    }
    ///////////////////////////////////////////////////////////////////////////

    ////////////// YOU MUST EDIT ONLY HERE ABOUT Assignment 2-2 ///////////////
    if (state.task_mode_13 == 0x01) // (brake on)
    {
        dutyRate = 0;
        R_GPT3->GTCCR[0] = Timer_Period_2ms * dutyRate / 100;
    }
    else // (brake off)
    {
        if (state.task_mode_12 == 0x01) // (accel on)
        {
            if (agt0_counter % 50 == 0) // 500ms
            {
                if (dutyRate < 100)
                {
                    dutyRate += 5;
                    R_GPT3->GTCCR[0] = Timer_Period_2ms * dutyRate / 100;
                }
                else
                {
                    dutyRate = 100;
                }
            }
        }
        else // task_mode_12 == 0x00 (accel off)
        {
            if (agt0_counter % 40 == 0) // 400ms
            {
                if (dutyRate > 0)
                {
                    dutyRate -= 5;
                    R_GPT3->GTCCR[0] = Timer_Period_2ms * dutyRate / 100;
                }
                else
                {
                    dutyRate = 0;
                }
            }
        }
    }
    ///////////////////////////////////////////////////////////////////////////
}
void R_AGT1_Interrupt(void)
{
    ////////////// YOU MUST EDIT ONLY HERE ABOUT Assignment 2-3 ///////////////
    agt1_counter++;
    if (state.task_mode_14 == 0x01) // (servo on)
    {
        if (agt1_counter % 20 == 0) // 200ms
        {
            if (rotate_mode == SERVO_ROTATE_RIGHT)
            {
                degree += 30;
                if (degree >= 180)
                {
                    rotate_mode = SERVO_ROTATE_LEFT;
                }
            }
            else // (servo_rotate_left)
            {
                degree -= 30;
                if (degree <= 0)
                {
                    rotate_mode = SERVO_ROTATE_RIGHT;
                    LED_PB00_Enable_Level = BSP_IO_LEVEL_HIGH;
                    R_IOPORT_PinWrite(&g_ioport_ctrl, led_pin[3], BSP_IO_LEVEL_HIGH);
                    state.task_mode_14 = 0x00;
                }
            }
        }
    }
    ///////////////////////////////////////////////////////////////////////////

    R_ICU->IELSR_b[5].IR = 0U; // Interrupt Controller Unit Flag Bit Clear
    Rotate_Servo();            // Servo Motor PWM Control Function
}

void R_GPT0_Setting() // Servo Motor PWM Generator
{
    R_GPT0->GTCR_b.MD = 0U;   // GPT32EH0 Count Mode Setting (Saw-wave PWM Mode)
    R_GPT0->GTCR_b.TPCS = 0U; // GPT32EH0 Clock Source Prescale Setting (PCLKD/1)

    R_GPT0->GTPR = Timer_Period_20ms - 1; // GPT32EH0 Counting Maximum Cycle Setting
    R_GPT0->GTCNT = 0;                    // GPT32EH0 Counter Initial Value Setting

    ////////////// YOU MUST EDIT ONLY HERE ABOUT Assignment 2-3 ///////////////
    R_GPT0->GTIOR_b.GTIOA = 9U;                                // GPT32EH0 Output Mode Setting (PWM Mode)
    R_GPT0->GTIOR_b.OAE = 1U;                                  // GPT32EH0 Output Enable Setting (Output Enable)
    R_GPT0->GTCCR[0] = Timer_Period_20ms * SERVO_MINIMUM_DUTY; // GPT32EH0 Initial Duty Setting
    R_GPT0->GTCR_b.CST = 1U;                                   // GPT32EH0 Count Start
    ///////////////////////////////////////////////////////////////////////////
}
void R_GPT3_Setting() // DC Motor PWM Generator
{
    R_GPT3->GTCR_b.MD = 0U;   // GPT32EH3 Count Mode Setting (Saw-wave PWM Mode)
    R_GPT3->GTCR_b.TPCS = 0U; // GPT32EH3 Clock Source Prescale Setting (PCLKD/1)

    R_GPT3->GTPR = Timer_Period_2ms - 1; // GPT32EH3 Counting Maximum Cycle Setting
    R_GPT3->GTCNT = 0U;                  // GPT32EH3 Counter Initial Value Setting

    ////////////// YOU MUST EDIT ONLY HERE ABOUT Assignment 2-2 ///////////////
    R_GPT3->GTIOR_b.GTIOA = 9U; // GPT32EH3 Output Mode Setting (PWM Mode)
    R_GPT3->GTIOR_b.OAE = 1U;   // GPT32EH3 Output Enable Setting (Output Enable)
    R_GPT3->GTCCR[0] = 0U;      // GPT32EH3 Initial Duty Setting
    R_GPT3->GTCR_b.CST = 1U;    // GPT32EH3 Count Start
    ///////////////////////////////////////////////////////////////////////////
}

void R_AGT1_Setting()
{
    R_MSTP->MSTPCRD_b.MSTPD2 = 0U; // AGT1 Module Stop State Cancel

    ////////////// YOU MUST EDIT ONLY HERE ABOUT Assignment 2-3 ///////////////
    NVIC->ISER[0] = 0x20;          // Interrupt Controller Unit Interrupt Enable
    NVIC->IP[5] = 0x0C;            // Interrupt Controller Unit Interrupt Priority Setting
    R_ICU->IELSR_b[5].IELS = 0x43; // Interrupt Controller Unit Interrupt Event Setting

    R_AGT1->AGTMR1_b.TMOD = 1U;  // AGT1 Timer Mode Setting (Pulse Output Mode)
    R_AGT1->AGTMR1_b.TCK = 4U;   // AGT1 Clock Source Setting (Divided clock AGTLCLK, LOCO 32.768 kHz)
    R_AGT1->AGTMR2_b.CKS = 3U;   // AGT1 Frequency Division Ratio Setting (Prescale = 8, 4.096 kHz)
    R_AGT1->AGT = 0x29;          // AGT1 Counter Initial Value Setting (0x29 = 41, 10 ms)
    R_AGT1->AGTCR_b.TSTART = 1U; // AGT1 Start Setting (Start AGT1 Counting)
    ///////////////////////////////////////////////////////////////////////////
}

// *******************************************************************************************************************/
// * This function is called at various points during the startup process.  This implementation uses the event that is
// * called right before main() to set up the pins.
// *
// * @param[in]  event    Where at in the start up process the code is currently at
// *******************************************************************************************************************/
void R_BSP_WarmStart(bsp_warm_start_event_t event)
{
    if (BSP_WARM_START_RESET == event)
    {
#if BSP_FEATURE_FLASH_LP_VERSION != 0

        /* Enable reading from data flash. */
        R_FACI_LP->DFLCTL = 1U;

        /* Would normally have to wait tDSTOP(6us) for data flash recovery. Placing the enable here, before clock and
         * C runtime initialization, should negate the need for a delay since the initialization will typically take more than 6us. */
#endif
    }

    if (BSP_WARM_START_POST_C == event)
    {
        /* C runtime environment and system clocks are setup. */

        /* Configure pins. */
        R_IOPORT_Open(&g_ioport_ctrl, g_ioport.p_cfg);
    }
}

