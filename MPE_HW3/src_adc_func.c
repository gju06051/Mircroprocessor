uint16_t potentiometer_mV = 0, potentiometer_Ra = 0, potentiometer_Rb = 0;
uint16_t temperature_mV; int16_t temperature;
uint16_t cds_data;

typedef enum {
    CDS_light = 0,
    CDS_dark = 1,
}CDS_t;

CDS_t brightness;

const float ADC_CONST = (float)(3.3/4096);

