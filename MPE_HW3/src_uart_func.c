#define STX                  0x02
#define ETX                  0x03
#define CARRIAGE_RETURN      0x0D
#define LINE_FEED            0x0A

#define MESSAGE_MAX_SIZE     50

char                         data[MESSAGE_MAX_SIZE] = {0};

char                         tail[2] = {CARRIAGE_RETURN, LINE_FEED};
char                         opcode[] = "LED";
volatile uint8_t             idx = 0;

/*******************************************************************************************************************//**
 * main() is generated by the RA Configuration editor and is used to generate threads if an RTOS is used.  This function
 * is called by main() when no RTOS is used.
 **********************************************************************************************************************/
void hal_entry(void)
{
    const char message[] = "Setting is complete.";

    R_SCI_UART_Open(&g_uart0_ctrl, &g_uart0_cfg);
    user_uart_write(message, strlen(message));

    while(true);

#if BSP_TZ_SECURE_BUILD
    /* Enter non-secure code */
    R_BSP_NonSecureEnter();
#endif
}

void user_uart_write(const char *msg, uint32_t const bytes)
{
    char *string = (char*)calloc(1, sizeof(char) * MESSAGE_MAX_SIZE);

    strcpy(string, msg);
    strcat(string, tail);

    R_SCI_UART_Write(&g_uart0_ctrl, (unsigned char*)string, bytes + 2);
    free(string);
}

void R_LED_Control(uint8_t number)
{
    switch(number)
    {
        case 0:
            R_PORT10->PCNTR1 = 0x07000700;
            R_PORT11->PCNTR1 = 0x00010001;
            break;
        case 1:
            R_PORT10->PCNTR1 = 0x06000700;
            R_PORT11->PCNTR1 = 0x00010001;
            break;
        case 2:
            R_PORT10->PCNTR1 = 0x05000700;
            R_PORT11->PCNTR1 = 0x00010001;
            break;
        case 3:
            R_PORT10->PCNTR1 = 0x03000700;
            R_PORT11->PCNTR1 = 0x00010001;
            break;
        case 4:
            R_PORT10->PCNTR1 = 0x07000700;
            R_PORT11->PCNTR1 = 0x00000001;
            break;
    }
}

void user_uart_callback(uart_callback_args_t *p_args)
{
    if(p_args->event == UART_EVENT_RX_CHAR) // If SDR (Serial Data Register) is charged, this event (UART_EVENT_RX_CHAR) is occurred.
    {
        switch(p_args->data)
        {
            case CARRIAGE_RETURN:
                break;
            case LINE_FEED:
                idx = 0;

                if(!strncmp((char *)&data[0], opcode, 2))
                    R_LED_Control((uint8_t)(data[3] - 48));

                memset(&data, 0, sizeof(data));
                break;
            default:
                data[idx++] = (char)p_args->data; // If Receive data Register is charged, take some data in byte.
                break;
        }
    }
}

/*******************************************************************************************************************//**
 * This function is called at various points during the startup process.  This implementation uses the event that is
 * called right before main() to set up the pins.
 *
 * @param[in]  event    Where at in the start up process the code is currently at
 **********************************************************************************************************************/
void R_BSP_WarmStart(bsp_warm_start_event_t event)
{
    if (BSP_WARM_START_RESET == event)
    {
#if BSP_FEATURE_FLASH_LP_VERSION != 0

        /* Enable reading from data flash. */
        R_FACI_LP->DFLCTL = 1U;

        /* Would normally have to wait tDSTOP(6us) for data flash recovery. Placing the enable here, before clock and
         * C runtime initialization, should negate the need for a delay since the initialization will typically take more than 6us. */
#endif
    }

    if (BSP_WARM_START_POST_C == event)
    {
        /* C runtime environment and system clocks are setup. */

        /* Configure pins. */
        R_IOPORT_Open (&g_ioport_ctrl, g_ioport.p_cfg);
    }
}

